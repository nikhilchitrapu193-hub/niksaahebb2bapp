// =============================================================================
// export-md.js — the Markdown export: an admin manual, a developer reference,
// one file per feature, an onboarding checklist per role and the migration
// guide. Same content as the website, for printing, Git diffs or pasting into
// a doc. Every answer keeps its source label, so a draft never reads as fact.
// =============================================================================

import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SOURCE = {
  annotation: 'reviewed', draft: 'draft — not yet checked by a person', stale: 'review needed — the code changed since it was reviewed',
  'code comment': 'from the code comment', permissions: 'from the live permission matrix', graph: 'from the database functions',
  database: 'messages from the database', troubleshooting: 'from the troubleshooting catalog',
};

function answerMd(a, docRequired) {
  if (a.missing) return `_${docRequired}_\n`;
  return a.parts.map((p) => {
    const tag = `*(${SOURCE[p.source] ?? p.source})*`;
    if (Array.isArray(p.value)) {
      if (p.value.length && typeof p.value[0] === 'object') return `${tag}\n\n${p.value.map((e) => `- **${e.symptom}** — ${e.solution}`).join('\n')}\n`;
      return `${tag}\n\n${p.value.map((s, i) => `${i + 1}. ${s}`).join('\n')}\n`;
    }
    return `${p.value} ${tag}\n`;
  }).join('\n');
}

export function featureMarkdown(k, f) {
  const lines = [`## ${f.name}`, '', `*${f.moduleLabel}* · ${f.screens.join(', ') || 'no screen'} · status: **${f.confidence}**${f.live.ready ? '' : ' · ⚠ not fully live in production'}`, ''];
  for (const q of k.questions) lines.push(`### ${q.q}`, '', answerMd(f.answers[q.key], k.docRequired));
  return `${lines.join('\n')}\n`;
}

function devMarkdown(k, f) {
  const l = [`## ${f.name} (\`${f.id}\`)`, ''];
  const row = (label, items) => { if (items.length) l.push(`- **${label}:** ${items.join(', ')}`); };
  row('Screens', f.screens);
  row('Files', f.files.map((p) => `\`${p}\``));
  row('api.js wrappers', f.wrappers.map((n) => `\`${n}()\` (line ${k.wrappers[n]?.line})`));
  row('Database functions', f.reach.functions.map((n) => `\`${n}()\``));
  row('Writes', f.tablesWritten);
  row('Reads', f.tablesRead);
  row('Storage', f.buckets);
  row('Edge Functions', f.edgeFunctions);
  row('Migrations', f.migrations);
  row('Page tests', f.pageTests.map((t) => `"${t}"`));
  row('Security checks', f.securityChecks.map((c) => c.id));
  row('Commits', f.commits);
  row('ADRs', f.adrs);
  if (!f.live.ready) l.push(`- **Not live:** ${[...f.live.missingFunctions, ...f.live.missingTables, ...f.live.missingEdge].join(', ')}`);
  for (const s of f.stale) l.push(`- **Stale:** ${s.why}`);
  return `${l.join('\n')}\n`;
}

export function onboardingMarkdown(k, role) {
  const o = k.onboarding[role];
  const l = [`# Onboarding: ${o.name}`, '', o.description, '', `Generated by AppAtlas from the live permission matrix (snapshot ${k.repoVsLive.liveGenerated ?? 'unknown'}).`, ''];
  o.features.forEach((id, i) => {
    const f = k.features[id];
    const what = f.answers.what_is_this.parts[0]?.value ?? k.docRequired;
    const steps = f.answers.workflow.parts[0]?.value ?? [];
    l.push(`- [ ] **${i + 1}. ${f.name}** (${f.moduleLabel}) — ${what}${steps.length ? ` First step: ${steps[0]}` : ''}`);
  });
  if (!o.features.length) l.push('This role has no screens in the admin app (it uses another app, or no permissions are ticked yet).');
  return `${l.join('\n')}\n`;
}

export function migrationGuideMarkdown(k) {
  const l = [`# Moving ${k.project.name} off Supabase`, '', 'Counted from the code; effort and alternatives come from the infrastructure annotations.', ''];
  for (const id of ['infra-supabase-auth', 'infra-supabase-postgres', 'infra-supabase-storage', 'infra-supabase-edge-functions']) {
    const f = k.features[id];
    if (!f) continue;
    const g = f.annotation?.admin?.migration_guide ?? {};
    l.push(`## ${f.name}`, '', `Effort: **${g.effort ?? '?'}** · Alternatives: ${(g.alternatives ?? []).join(', ') || k.docRequired}`, '');
    if (g.what_changes_for_admin) l.push(`For admins: ${g.what_changes_for_admin}`, '');
    if (g.what_stays_same) l.push(`Stays the same: ${g.what_stays_same}`, '');
    for (const c of f.annotation?.developer?.code_to_replace ?? []) l.push(`- replace \`${c}\``);
    l.push('');
  }
  const i = k.infra;
  l.push('## Counted facts', '',
    `- Postgres: ${i.postgres.tables} tables/views, ${i.postgres.functions} functions (${i.postgres.definer} SECURITY DEFINER), ${i.postgres.policies} policies, ${i.postgres.triggers} triggers, ${i.postgres.migrations} migrations — plain SQL.`,
    `- Auth: ${i.auth.sqlFunctionsUsingAuthUid.length} SQL functions call auth.uid(); browser files: ${i.auth.files.join(', ')}; Edge Functions using the admin API: ${i.auth.edgeFunctions.join(', ')}.`,
    `- Storage: buckets ${i.storage.buckets.map((b) => `${b.name}${b.public ? ' (public)' : ''}`).join(', ')}; wrappers: ${i.storage.wrappers.map((w) => w.name).join(', ')}.`,
    `- Edge Functions: ${i.edge.map((e) => `${e.name}${e.deployed ? '' : ' (not deployed)'} [${e.secrets.filter((s) => !s.startsWith('SUPABASE_')).join(', ') || 'no extra secrets'}]`).join('; ')}.`, '');
  return `${l.join('\n')}\n`;
}

export function writeMarkdown(k, dir) {
  mkdirSync(join(dir, 'features'), { recursive: true });
  mkdirSync(join(dir, 'onboarding'), { recursive: true });
  const list = Object.values(k.features).sort((a, b) => a.areaLabel.localeCompare(b.areaLabel) || a.moduleLabel.localeCompare(b.moduleLabel) || a.name.localeCompare(b.name));
  writeFileSync(join(dir, 'admin-manual.md'), `# ${k.project.name} — admin manual\n\nGenerated by AppAtlas. Each answer says where it came from.\n\n${list.map((f) => featureMarkdown(k, f)).join('\n')}`);
  writeFileSync(join(dir, 'developer-reference.md'), `# ${k.project.name} — developer reference\n\n${list.map((f) => devMarkdown(k, f)).join('\n')}`);
  for (const f of list) writeFileSync(join(dir, 'features', `${f.id}.md`), `${featureMarkdown(k, f)}\n${devMarkdown(k, f)}`);
  for (const role of Object.keys(k.onboarding)) writeFileSync(join(dir, 'onboarding', `${role}.md`), onboardingMarkdown(k, role));
  writeFileSync(join(dir, 'migration-guide.md'), migrationGuideMarkdown(k));
}
